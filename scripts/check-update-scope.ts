import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { isAllowedUpdateFile, type UpdateMode } from "./update-scope-policy";
const mode=process.argv.includes("--mode")?process.argv[process.argv.indexOf("--mode")+1] as UpdateMode:undefined;
if(!mode||!["news","law"].includes(mode))throw new Error("Use --mode news or --mode law");
const repository=resolve(".").replace(/\\/g,"/");
const base=process.argv.includes("--base")?process.argv[process.argv.indexOf("--base")+1]:undefined;
const working=execFileSync("git",["-c",`safe.directory=${repository}`,"status","--porcelain"],{encoding:"utf8"}).split(/\r?\n/).filter(Boolean).map((line)=>line.slice(3).replace(/\\/g,"/"));
const committed=base?execFileSync("git",["-c",`safe.directory=${repository}`,"diff","--name-only",`${base}...HEAD`],{encoding:"utf8"}).split(/\r?\n/).filter(Boolean).map((line)=>line.replace(/\\/g,"/")):[];
const changed=[...new Set([...committed,...working])];
const violations=changed.filter((file)=>!isAllowedUpdateFile(mode,file));
if(violations.length)throw new Error(`${mode} workflow changed files outside its allowlist:\n- ${violations.join("\n- ")}`);
console.log(JSON.stringify({status:"PASS",mode,files:changed}));
